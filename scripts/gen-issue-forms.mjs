// Generates the Issue Forms (.github/ISSUE_TEMPLATE) from worlds, tags, dictionaries and config.
// Usage: npm run gen:forms            write the forms
//        node scripts/gen-issue-forms.mjs --check   only compare (X22, part of npm run check)
// Output uses a minimal YAML writer: every string is a double-quoted JSON string.

import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { parseArgs } from "node:util";
import { DIMENSION_ORDER } from "../site/js/lib/coords.js";
import { LABELS } from "../site/js/lib/forms-meta.js";
import { dimensionName } from "./lib/changelog-templates.mjs";
import { FORMS, REQUEST_KINDS } from "./lib/form-fields.mjs";
import { REPO_ROOT, createFsReader, loadDataset } from "./lib/load-data.mjs";

export const TEMPLATE_DIR = ".github/ISSUE_TEMPLATE";
const HEADER = "# Generated by scripts/gen-issue-forms.mjs from site/data. Do not edit by hand; run npm run gen:forms.";

// ---------------------------------------------------------------------------
// Minimal YAML writer (mappings, sequences, strings, numbers, booleans)

const KEY_RE = /^[A-Za-z_][A-Za-z0-9_-]*$/;

/** Double-quoted YAML scalar via JSON (line and paragraph separators escaped too). */
export function yamlScalar(value) {
  if (typeof value === "string") return JSON.stringify(value).replace(/\u2028/g, "\\u2028").replace(/\u2029/g, "\\u2029");
  if (typeof value === "number" && Number.isFinite(value)) return String(value);
  if (typeof value === "boolean") return value ? "true" : "false";
  throw new TypeError(`Unsupported YAML value: ${value}`);
}

const isScalar = (v) => typeof v === "string" || typeof v === "number" || typeof v === "boolean";
const yamlKey = (key) => (KEY_RE.test(key) ? key : JSON.stringify(key));

function mappingLines(object, indent) {
  const pad = " ".repeat(indent);
  const lines = [];
  for (const [key, value] of Object.entries(object)) {
    if (value === undefined) continue;
    if (isScalar(value)) {
      lines.push(`${pad}${yamlKey(key)}: ${yamlScalar(value)}`);
    } else if (Array.isArray(value)) {
      if (value.length === 0) {
        lines.push(`${pad}${yamlKey(key)}: []`);
        continue;
      }
      lines.push(`${pad}${yamlKey(key)}:`);
      for (const item of value) {
        if (isScalar(item)) {
          lines.push(`${pad}  - ${yamlScalar(item)}`);
        } else {
          const itemLines = mappingLines(item, indent + 4);
          itemLines[0] = `${pad}  - ${itemLines[0].trimStart()}`;
          lines.push(...itemLines);
        }
      }
    } else if (value !== null && typeof value === "object") {
      lines.push(`${pad}${yamlKey(key)}:`, ...mappingLines(value, indent + 2));
    } else {
      throw new TypeError(`Unsupported YAML value for ${key}`);
    }
  }
  return lines;
}

/** YAML document for a plain object, with the generated-file header. */
export function toYaml(object) {
  return `${HEADER}\n${mappingLines(object, 0).join("\n")}\n`;
}

// ---------------------------------------------------------------------------
// Form content

const bilingual = (en, zh) => `${en} / ${zh}`;
const escapeTableText = (text) => String(text).replace(/\\/g, "\\\\").replace(/\|/g, "\\|");

function editionLabel(id, dictionaries) {
  const en = dictionaries?.en?.messages?.[`edition.${id}`] ?? id;
  const zh = dictionaries?.["zh-TW"]?.messages?.[`edition.${id}`] ?? id;
  return bilingual(en, zh);
}

/** Active (not retired) tags ordered by group order, then by their order in tags.json. */
export function activeTags(tags) {
  const groupRank = new Map(tags.groups.map((g, i) => [g.id, i]));
  return tags.tags
    .map((tag, i) => ({ tag, i }))
    .filter(({ tag }) => !tag.retired)
    .sort((a, b) => (groupRank.get(a.tag.group) ?? 0) - (groupRank.get(b.tag.group) ?? 0) || a.i - b.i)
    .map(({ tag }) => tag);
}

/** Dropdown options; every option ends with "(id)", which the parser reads back. */
export function buildOptions(dataset) {
  const dictionaries = dataset.i18n;
  return {
    worlds: dataset.worlds.worlds.map((w) => `${w.name} (${w.id})`),
    dimensions: DIMENSION_ORDER.map((d) => `${bilingual(dimensionName(d, "en", dictionaries), dimensionName(d, "zh-TW", dictionaries))} (${d})`),
    tags: activeTags(dataset.tags).map((t) => `${bilingual(t.name.en, t.name["zh-TW"])} (${t.id})`),
  };
}

/** Markdown table: which dimensions (and editions) each active tag is allowed in. */
export function buildTagTable(dataset) {
  const dictionaries = dataset.i18n;
  const dims = DIMENSION_ORDER.map((d) => bilingual(dimensionName(d, "en", dictionaries), dimensionName(d, "zh-TW", dictionaries)));
  const lines = [
    "**Tags by dimension / 各維度可用標籤**",
    "",
    `| Tag / 標籤 | ${dims.join(" | ")} | Editions / 版本 |`,
    `| --- | ${DIMENSION_ORDER.map(() => ":-:").join(" | ")} | --- |`,
  ];
  for (const tag of activeTags(dataset.tags)) {
    const marks = DIMENSION_ORDER.map((d) => (tag.dimensions.includes(d) ? "✓" : "—"));
    const editions = tag.editions ? tag.editions.map((e) => editionLabel(e, dictionaries)).join(", ") : bilingual("All", "全部");
    lines.push(`| ${escapeTableText(bilingual(tag.name.en, tag.name["zh-TW"]))} (\`${tag.id}\`) | ${marks.join(" | ")} | ${escapeTableText(editions)} |`);
  }
  return lines.join("\n");
}

function formBodyItem(field, context, options) {
  const required = field.required ? { validations: { required: true } } : {};
  switch (field.type) {
    case "markdown":
      return { type: "markdown", attributes: { value: field.value(context) } };
    case "dropdown": {
      const list = options[field.options];
      const attributes = { label: field.label, description: field.description, multiple: field.multiple ? true : undefined, options: list };
      if (field.options === "worlds" && list.length === 1) attributes.default = 0;
      return { type: "dropdown", id: field.id, attributes, ...required };
    }
    case "input":
      return { type: "input", id: field.id, attributes: { label: field.label, description: field.description, placeholder: field.placeholder }, ...required };
    case "textarea":
      return { type: "textarea", id: field.id, attributes: { label: field.label, description: field.description }, ...required };
    case "checkboxes":
      return { type: "checkboxes", id: field.id, attributes: { label: field.label, options: [{ label: field.option, required: true }] } };
    default:
      throw new Error(`Unknown field type: ${field.type}`);
  }
}

/** Issue form object for a request kind. */
export function buildForm(kind, dataset) {
  const form = FORMS[kind];
  const context = { config: dataset.config, tagTable: buildTagTable(dataset) };
  const options = buildOptions(dataset);
  if (form.labels.includes(LABELS.approved)) throw new Error("Issue forms must never apply the approved label");
  return {
    name: form.name,
    description: form.description,
    title: form.title,
    labels: [...form.labels],
    body: form.fields.map((field) => formBodyItem(field, context, options)),
  };
}

/** config.yml: blank issues disabled; links to the website and the Discord invite (from config). */
export function buildConfig(dataset) {
  return {
    blank_issues_enabled: false,
    contact_links: [
      {
        name: bilingual("Coordinate website", "座標網站"),
        url: dataset.config.siteUrl,
        about: bilingual(
          "Browse every coordinate; the card menus prefill edit and delete requests.",
          "瀏覽所有座標；卡片選單可預填修改與刪除請求。",
        ),
      },
      {
        name: bilingual("No GitHub account? Join Discord", "沒有 GitHub 帳號？加入 Discord"),
        url: dataset.config.discordInviteUrl,
        about: bilingual("Join the community Discord and ask the owner to add your coordinate.", "加入社群 Discord，請擁有者代為登錄座標。"),
      },
    ],
  };
}

/**
 * Every generated file as { path (repo-relative, forward slashes), content }.
 * @param {object} dataset needs config, worlds, tags; dictionaries are optional (built-in names otherwise)
 */
export function buildIssueForms(dataset) {
  const files = REQUEST_KINDS.map((kind) => ({ path: `${TEMPLATE_DIR}/${FORMS[kind].file}`, content: toYaml(buildForm(kind, dataset)) }));
  files.push({ path: `${TEMPLATE_DIR}/config.yml`, content: toYaml(buildConfig(dataset)) });
  return files;
}

/** File access used by run (replaceable in tests). read returns null when the file is missing. */
export const fsIo = {
  async read(filePath) {
    try {
      return await readFile(filePath, "utf8");
    } catch (error) {
      if (error.code === "ENOENT") return null;
      throw error;
    }
  },
  async write(filePath, content) {
    await mkdir(path.dirname(filePath), { recursive: true });
    await writeFile(filePath, content, "utf8");
  },
};

export async function run({ argv = process.argv.slice(2), root = REPO_ROOT, log = console.log, reader = createFsReader(root), io = fsIo } = {}) {
  const { values } = parseArgs({ args: argv, options: { check: { type: "boolean", default: false } } });
  const { dataset, issues } = await loadDataset(reader);
  if (!dataset.config || !dataset.worlds || !dataset.tags) {
    for (const issue of issues) log(`ERROR   ${issue.file}: ${issue.message}`);
    log("Issue forms: data could not be loaded");
    return 1;
  }
  const files = buildIssueForms(dataset);
  let differences = 0;
  for (const file of files) {
    const target = path.join(root, file.path);
    const current = await io.read(target);
    if (current === file.content) continue;
    differences += 1;
    if (values.check) {
      log(`ERROR   X22    ${file.path}  ${current === null ? "is missing" : "is out of date"}; run npm run gen:forms`);
    } else {
      await io.write(target, file.content);
      log(`Wrote ${file.path}`);
    }
  }
  if (values.check) {
    log(`Issue forms: ${differences === 0 ? "up to date" : `${differences} file(s) out of date`}`);
    return differences === 0 ? 0 : 1;
  }
  log(`Issue forms: ${differences} file(s) written`);
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.exitCode = await run();
}
